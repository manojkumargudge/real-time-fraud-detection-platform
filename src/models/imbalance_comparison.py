"""Class-imbalance comparison: ``scale_pos_weight`` (current) vs ``none`` (weight 1).

Usage: ``python -m src.models.imbalance_comparison`` trains the baseline once per method and
seed, sequentially (one model in memory at a time), logs every run to MLflow
(``src.models.tracking``), and writes ``reports/imbalance_comparison.md``. Candidate bundles go
to ``artifacts/candidates/`` (gitignored); the served ``artifacts/baseline/`` is never touched.

Champion rule: the ``champion`` alias moves only if the challenger (``none``) beats the
current method on mean validation PR-AUC by more than the seed spread, defined as the larger
of the two methods' max-minus-min PR-AUC across seeds. ROC-AUC is logged for reference only.
"""

from __future__ import annotations

import argparse
import gc
import logging
from dataclasses import dataclass
from pathlib import Path
from statistics import mean

from src.data.load import DEFAULT_RAW_DIR, load_ieee_cis
from src.models.compare import ComparisonConfig
from src.models.train import fit_baseline, save_bundle

logger = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[2]
REPORT = REPO_ROOT / "reports" / "imbalance_comparison.md"
CANDIDATES = REPO_ROOT / "artifacts" / "candidates"
CURRENT, CHALLENGER = "scale_pos_weight", "none"
SEEDS = (42, 7, 2026)
BUDGET = "1pct"


@dataclass(frozen=True)
class RunResult:
    method: str
    seed: int
    run_id: str
    scale_pos_weight: float
    metrics: dict[str, float]


@dataclass(frozen=True)
class Decision:
    current_mean: float
    challenger_mean: float
    difference: float  # challenger - current
    seed_spread: float
    move_champion: bool


def decide(results: list[RunResult]) -> Decision:
    by_method = {
        m: [r.metrics["valid_pr_auc"] for r in results if r.method == m]
        for m in (CURRENT, CHALLENGER)
    }
    if not all(by_method.values()):
        raise ValueError("need at least one run per method")
    spread = max(max(v) - min(v) for v in by_method.values())
    cur, chal = mean(by_method[CURRENT]), mean(by_method[CHALLENGER])
    return Decision(cur, chal, chal - cur, spread, chal - cur > spread)


def _summary_rows(results: list[RunResult]) -> list[str]:
    rows = []
    for method in (CURRENT, CHALLENGER):
        rs = [r for r in results if r.method == method]

        def avg(key: str, rs: list[RunResult] = rs) -> float:
            return mean(r.metrics[key] for r in rs)

        pr = [r.metrics["valid_pr_auc"] for r in rs]
        rows.append(
            f"| `{method}` | {rs[0].scale_pos_weight:.2f} | {len(rs)} | {mean(pr):.4f} | "
            f"{min(pr):.4f} | {max(pr):.4f} | {avg('valid_precision_at_threshold'):.4f} | "
            f"{avg('valid_recall_at_threshold'):.4f} | "
            f"{avg('valid_alert_rate_at_threshold'):.2%} | "
            f"{avg(f'valid_precision_at_budget_{BUDGET}'):.4f} | "
            f"{avg(f'valid_recall_at_budget_{BUDGET}'):.4f} | {avg('valid_roc_auc'):.4f} | "
            f"{avg('train_seconds'):.0f} |"
        )
    return rows


def render(results: list[RunResult], decision: Decision, champion_note: str) -> str:
    better = CHALLENGER if decision.difference > 0 else CURRENT
    bigger = "larger" if abs(decision.difference) > decision.seed_spread else "not larger"
    lines = [
        "# Class-imbalance comparison",
        "",
        f"Baseline XGBoost, same features and chronological split; methods `{CURRENT}` "
        f"(current: negatives / positives of the training rows) and `{CHALLENGER}` (weight 1); "
        f"seeds {', '.join(map(str, SEEDS))}; trained one at a time; every run logged to MLflow "
        "experiment `fraud-xgboost`. Generated by `python -m src.models.imbalance_comparison`.",
        "",
        "Operating points: *threshold* = each run's own max-F1 threshold from the training "
        "holdout (the serving alert rule); *1% budget* = alert on the top 1% of validation "
        "scores (Milestone 2.2 budget).",
        "",
        "| Method | Weight | Runs | Mean PR-AUC | Min | Max | Precision @ threshold | "
        "Recall @ threshold | Alert rate @ threshold | Precision @ 1% budget | "
        "Recall @ 1% budget | ROC-AUC (ref.) | Mean train s |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        *_summary_rows(results),
        "",
        f"`{better}` has the higher mean validation PR-AUC "
        f"({decision.challenger_mean:.4f} for `{CHALLENGER}` vs {decision.current_mean:.4f} for "
        f"`{CURRENT}`, difference {decision.difference:+.4f}). "
        f"The difference is {bigger} than the seed-to-seed spread ({decision.seed_spread:.4f}, "
        "the larger max-minus-min PR-AUC across seeds of the two methods). "
        "ROC-AUC is shown for reference but not used for the decision, because with about 3.5% "
        "fraud it is dominated by the many easy negatives and hides differences in the "
        "high-score region that alerting depends on.",
        "",
        f"Champion: {champion_note}",
        "",
        "## Runs",
        "",
        "| Method | Seed | PR-AUC | ROC-AUC | MLflow run |",
        "|---|---|---|---|---|",
        *(
            f"| `{r.method}` | {r.seed} | {r.metrics['valid_pr_auc']:.4f} | "
            f"{r.metrics['valid_roc_auc']:.4f} | `{r.run_id}` |"
            for r in results
        ),
        "",
    ]
    return "\n".join(lines)


def main(raw_dir: Path = DEFAULT_RAW_DIR, report: Path = REPORT) -> Decision:
    # Imported here so the module (and its unit tests) load without an MLflow store.
    from mlflow.tracking import MlflowClient

    from src.models import tracking

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s %(message)s")
    df = load_ieee_cis(raw_dir, usecols=[])
    results: list[RunResult] = []
    for method in (CURRENT, CHALLENGER):
        for seed in SEEDS:
            run = fit_baseline(df, ComparisonConfig(seed=seed, imbalance=method))
            bundle = save_bundle(run.trained, run.metadata, CANDIDATES / f"{method}-seed{seed}")
            run_id = tracking.log_training_run(run, bundle, imbalance_method=method)
            results.append(
                RunResult(
                    method,
                    seed,
                    run_id,
                    float(run.metadata["scale_pos_weight"]),
                    tracking.run_metrics(run),
                )
            )
            logger.info(
                "done method=%s seed=%d pr_auc=%.4f",
                method,
                seed,
                results[-1].metrics["valid_pr_auc"],
            )
            del run
            gc.collect()

    decision = decide(results)
    uri = tracking.tracking_uri()
    client = MlflowClient(tracking_uri=uri, registry_uri=uri)
    if decision.move_champion:
        best = max(
            (r for r in results if r.method == CHALLENGER), key=lambda r: r.metrics["valid_pr_auc"]
        )
        version = tracking.register_champion(client, best.run_id)
        note = (
            f"moved to `{CHALLENGER}` seed {best.seed} (registered as `fraud-xgboost` version "
            f"{version}); the served bundle in `artifacts/baseline/` is unchanged until deployed."
        )
    else:
        current = client.get_model_version_by_alias(tracking.MODEL_NAME, tracking.CHAMPION_ALIAS)
        note = (
            f"unchanged; `{CHALLENGER}` does not beat `{CURRENT}` by more than the seed spread, "
            f"so `fraud-xgboost` version {current.version} (run `{current.run_id}`) stays "
            "`champion`."
        )
    report.write_text(render(results, decision, note), encoding="utf-8")
    logger.info("wrote %s decision=%s", report, decision)
    return decision


if __name__ == "__main__":
    argparse.ArgumentParser(description=__doc__).parse_args()
    main()
